import { TraceCase, TraceDebugResult, TraceStep } from './trace.types';

type TraceSeed = Omit<TraceStep, 'responseId'>;

const baseTimestamp = 'May 27, 17:35:28.082';
const toolTimestamp = 'May 27, 12:21:02.268';

function createStep(responseId: string, seed: TraceSeed): TraceStep {
  return { ...seed, responseId };
}

function createCase(
  id: string,
  label: string,
  scenario: string,
  samplePrompt: string,
  assistantResponse: string,
  steps: TraceSeed[],
): TraceCase {
  return {
    id,
    label,
    scenario,
    samplePrompt,
    assistantResponse,
    steps: steps.map((step) => createStep(id, step)),
  };
}

