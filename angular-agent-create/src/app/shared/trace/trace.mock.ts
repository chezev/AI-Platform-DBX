export function getTraceCase(caseId: string): TraceCase {
  return TRACE_CASES.find((traceCase) => traceCase.id === caseId) ?? TRACE_CASES[0];
}

export function cloneTraceStepsForResponse(caseId: string, responseId: string): TraceStep[] {
  return getTraceCase(caseId).steps.map((step) => ({
    ...step,
    id: `${responseId}-${step.sequence}`,
    responseId,
  }));
}

export function pickTraceCaseIdForPrompt(prompt: string): string {
  const query = prompt.toLowerCase();

  if (query.includes('approval') || query.includes('approve')) return 'human-approval';
  if (query.includes('retry')) return 'retry-flow';
  if (query.includes('fail') || query.includes('timeout') || query.includes('api')) return 'tool-failure';
  if (query.includes('resume') || query.includes('attach') || query.includes('file')) return 'file-resume-parse';
  if (query.includes('token') || query.includes('policy') || query.includes('summarize')) return 'high-token-usage';
  if (query.includes('buddy') || query.includes('setup')) return 'tool-success';
  if (query.includes('if') || query.includes('condition')) return 'conditional-branch';
  if (query.includes('candidate') || query.includes('onboard')) return 'missing-input';

  return 'simple-llm-response';
}

export function buildTraceDebugResult(steps: TraceStep[], selectedStep?: TraceStep): TraceDebugResult {
  const failedStep = selectedStep?.status === 'failed' ? selectedStep : steps.find((step) => step.status === 'failed');
  const waitingStep = selectedStep?.status === 'waiting' ? selectedStep : steps.find((step) => step.status === 'waiting');
  const highTokenStep = selectedStep?.totalTokens && selectedStep.totalTokens > 3000
    ? selectedStep
    : steps.find((step) => (step.totalTokens ?? 0) > 3000);
  const contextStep = selectedStep ?? failedStep ?? waitingStep ?? highTokenStep ?? steps[0];
  const contextLabel = selectedStep ? contextStep.title : 'Full Trace';

  if (failedStep) {
    return {
      title: selectedStep ? `Debug: ${contextStep.title}` : 'Debug Full Trace',
      contextLabel,
      happened: 'The agent understood the request and started the expected workflow.',
      issue: `The issue happened at ${failedStep.title}.`,
      reason: failedStep.error?.message ?? 'The connected action failed before the workflow could finish.',
      fix: 'Retry the action once. If it fails again, check the tool connection and API health.',
      nextAction: 'Retry or contact the workflow admin if the API keeps timing out.',
    };
  }

  if (waitingStep) {
    return {
      title: selectedStep ? `Debug: ${contextStep.title}` : 'Debug Full Trace',
      contextLabel,
      happened: 'The agent reached a governed workflow step.',
      issue: `The workflow is paused at ${waitingStep.title}.`,
      reason: 'The policy check requires HR Admin approval before the agent can continue.',
      fix: 'Ask the approver to approve the request, then resume the workflow.',
      nextAction: 'Wait for approval or contact the HR Admin.',
    };
  }

  if (highTokenStep) {
    return {
      title: selectedStep ? `Debug: ${contextStep.title}` : 'Debug Full Trace',
      contextLabel,
      happened: 'The agent searched a broad knowledge context before answering.',
      issue: `${highTokenStep.title} used ${highTokenStep.totalTokens} total tokens.`,
      reason: 'Knowledge search returned large context and the model processed most of it.',
      fix: 'Narrow the knowledge source, filter by policy type, or summarize retrieved context before the final response.',
      nextAction: 'Edit the prompt or reduce retrieval scope before retrying.',
    };
  }

  return {
    title: selectedStep ? `Debug: ${contextStep.title}` : 'Debug Full Trace',
    contextLabel,
    happened: selectedStep ? contextStep.summary ?? 'This step completed successfully.' : 'All trace steps completed without blocking errors.',
    issue: 'No failure was detected in this trace.',
    reason: 'The agent used the expected model and action path for this request.',
    fix: 'No fix is required. You can inspect raw logs if you need deeper validation.',
    nextAction: 'Continue, or copy the trace if you need to share it with an admin.',
  };
}
